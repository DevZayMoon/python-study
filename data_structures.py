# uma lista é ordenada
# uma lista é mutável

lista = [] # declarando uma lista vazia

lista = [1, "Python", 2] # atribuindo valores à lista

lista[0] # acessando um valor da lista pelo seu índice

lista[0] = "JavaScript is better" # alterando um valor de um elemento pelo seu índice (index)

lista.append('Java') # adicionando um novo elemento ao final da lista (list)

lista.insert(1, "C#") # adicionando um elemento em um índice específico. Caso haja um elemento nesse índice, ele será empurrado para frente

